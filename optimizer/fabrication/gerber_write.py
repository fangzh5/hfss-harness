from __future__ import annotations

from pathlib import Path

from .model import BoardOutline, Polygon
from .validation import contour_errors


def format_coord(value: float) -> str:
    scaled = int(round(float(value) * 1000))
    sign = "-" if scaled < 0 else ""
    return f"{sign}{abs(scaled):06d}"


def _xy(point: list[float]) -> str:
    return f"X{format_coord(point[0])}Y{format_coord(point[1])}"


def write_copper_gerber(output_path: str | Path, layer_name: str, polygons: list[Polygon]) -> None:
    output = Path(output_path)
    output.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "G04 Generated by hfss-harness fabrication flow*",
        "%FSLAX33Y33*%",
        "%MOMM*%",
        "%LPD*%",
        "%ADD10C,0.0100*%",
        "D10*",
        f"G04 Layer {layer_name}*",
    ]
    current_polarity = "dark"
    for polygon in polygons:
        if len(polygon.points) < 3:
            continue
        polarity = "clear" if polygon.polarity == "clear" else "dark"
        if polarity != current_polarity:
            lines.append("%LPC*%" if polarity == "clear" else "%LPD*%")
            current_polarity = polarity
        lines.append("G36*")
        lines.append(f"{_xy(polygon.points[0])}D02*")
        for point in polygon.points[1:]:
            lines.append(f"{_xy(point)}D01*")
        lines.append(f"{_xy(polygon.points[0])}D01*")
        lines.append("G37*")
    if current_polarity != "dark":
        lines.append("%LPD*%")
    lines.append("M02*")
    output.write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_outline_gerber(output_path: str | Path, outline: BoardOutline) -> None:
    errors = contour_errors(outline.points)
    if errors:
        raise ValueError("Invalid board profile: " + "; ".join(errors))
    points = list(outline.points)
    if points[0] == points[-1]: points.pop()
    output = Path(output_path)
    output.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "G04 Generated by hfss-harness fabrication flow*",
        "%FSLAX33Y33*%",
        "%MOMM*%",
        "%TF.FileFunction,Profile,NP*%",
        "%LPD*%",
        "%ADD10C,0.0500*%",
        "D10*",
        "G04 Board outline*",
    ]
    lines.append(f"{_xy(points[0])}D02*")
    for point in points[1:]:
        lines.append(f"{_xy(point)}D01*")
    lines.append(f"{_xy(points[0])}D01*")
    lines.append("M02*")
    output.write_text("\n".join(lines) + "\n", encoding="utf-8")
